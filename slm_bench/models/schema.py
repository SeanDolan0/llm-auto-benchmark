"""
Standardized JSON Schema definitions for SLM Benchmark Results (Schema Version 2.0.0).
Provides verifiable provenance, statistical confidence intervals, evaluation status (FULL/PARTIAL/INVALID),
fine-grained question logging, and hardware telemetry.
"""

from typing import Dict, List, Optional, Any, Union
from pydantic import BaseModel, Field
from datetime import datetime, timezone


class HardwareInfo(BaseModel):
    """Host environment and hardware specifications."""
    os: str = Field(..., description="Operating system name and version")
    cpu: str = Field(..., description="Processor name")
    cpu_cores: int = Field(..., description="Logical CPU cores count")
    total_ram_gb: float = Field(..., description="Total system RAM in GB")
    model_ram_gb: Optional[float] = Field(None, description="Size in RAM / VRAM in GB that the model takes up")
    gpu_name: Optional[str] = Field(None, description="Primary GPU model name")
    gpu_count: int = Field(0, description="Number of detected GPUs")
    gpu_vram_gb: Optional[float] = Field(None, description="Primary GPU VRAM in GB")
    cuda_version: Optional[str] = Field(None, description="Detected CUDA runtime version")
    driver_version: Optional[str] = Field(None, description="GPU Driver version")


class ModelMetadata(BaseModel):
    """Model identity, parameter estimates, and architecture details."""
    model_id: str = Field(..., description="Hugging Face repository ID or model path")
    model_slug: str = Field(..., description="URL and branch safe slug")
    param_count_b: Optional[float] = Field(None, description="Estimated/retrieved parameters in billions")
    param_tier: str = Field(..., description="Parameter tier: <3B, 3B-8B, 8B-14B, 14B-35B, 35B-50B, >50B")
    architecture: Optional[str] = Field(None, description="Model architecture type")
    quantization: str = Field("BF16", description="Quantization method (e.g., GGUF_Q4_K_M, AWQ_4BIT, NF4, BF16)")
    model_ram_gb: Optional[float] = Field(None, description="Size in RAM / VRAM in GB that the model takes up")
    context_length: Optional[int] = Field(None, description="Maximum context window in tokens")
    license: Optional[str] = Field(None, description="Model license")
    backend: str = Field(..., description="Inference backend used for evaluation")
    backend_version: Optional[str] = Field(None, description="Version of the inference engine/library")
    reasoning_effort: Optional[str] = Field(None, description="Reasoning effort level (none, minimal, low, medium, high, xhigh, or max; model-dependent)")


class QuestionResult(BaseModel):
    """Fine-grained evaluation provenance for a single benchmark question."""
    question_id: str = Field(..., description="Unique dataset question or prompt identifier")
    raw_prompt: str = Field(..., description="Actual prompt submitted to the model")
    raw_response: str = Field(..., description="Raw output generated by the model")
    extracted_answer: Optional[str] = Field(None, description="Deterministic extracted answer")
    expected_answer: Optional[str] = Field(None, description="Ground truth answer or expected value")
    is_correct: bool = Field(..., description="Evaluation outcome")
    reused: bool = Field(False, description="Whether this result was served from a replay checkpoint")
    evaluation_error: Optional[str] = Field(None, description="Evaluation or execution error if any")
    tokens_prompt: Optional[int] = Field(None, description="Input tokens count")
    tokens_generated: Optional[int] = Field(None, description="Generated tokens count")
    latency_ms: Optional[float] = Field(None, description="Generation latency in milliseconds")


class TaskMetric(BaseModel):
    """Detailed score and provenance for an individual benchmark task."""
    task_id: str = Field(..., description="Unique task identifier (e.g. mmlu_pro, gpqa_diamond, gsm8k)")
    category: str = Field(..., description="Category: reasoning, mathematics, coding, instruction, tool_calling, context, safety")
    status: str = Field("FULL", description="Evaluation status: FULL, PARTIAL, INVALID, UNAVAILABLE")
    raw_score: float = Field(..., description="Raw metric value (e.g. accuracy fraction, pass@1)")
    raw_metric_name: str = Field("accuracy", description="Metric type: accuracy, pass@1, compliance_rate, etc.")
    normalized_score: float = Field(..., ge=0.0, le=100.0, description="Normalized score 0.0 - 100.0%")
    total_samples: int = Field(..., description="Number of test items evaluated")
    passed_samples: int = Field(..., description="Number of passed test items")
    failed_samples: int = Field(0, description="Number of failed test items")
    invalid_responses: int = Field(0, description="Number of malformed or ambiguous unparsable outputs")
    ci_lower: Optional[float] = Field(None, description="Wilson score 95% confidence interval lower bound (%)")
    ci_upper: Optional[float] = Field(None, description="Wilson score 95% confidence interval upper bound (%)")
    dataset_name: Optional[str] = Field(None, description="Official dataset identifier")
    dataset_revision: Optional[str] = Field(None, description="Pinned dataset commit or revision tag")
    split: Optional[str] = Field(None, description="Dataset split evaluated (e.g. test, diamond)")
    avg_latency_ms: Optional[float] = Field(None, description="Average response latency in milliseconds")
    avg_tokens_per_sec: Optional[float] = Field(None, description="Average generation speed in tokens/second")
    sub_metrics: Dict[str, Any] = Field(default_factory=dict, description="Fine-grained metric breakdowns (by subject/difficulty)")
    question_results: Optional[List[QuestionResult]] = Field(default=None, description="Individual question results for auditability")


class CategoryScore(BaseModel):
    """Aggregated score for a high-level benchmark pillar."""
    category: str
    weight: float = Field(..., description="Weight in the composite index (0.0 - 1.0)")
    normalized_score: float = Field(..., ge=0.0, le=100.0, description="Average score 0.0 - 100.0%")
    task_count: int
    tasks: List[str] = Field(default_factory=list, description="IDs of tasks contributing to this category")


class BenchmarkResult(BaseModel):
    """Standardized root JSON result structure for a benchmarked model (Schema 2.0.0)."""
    schema_version: str = Field("2.0.0", description="Schema version identifier")
    evaluation_id: str = Field(..., description="Unique UUID for evaluation run")
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    status: str = Field("FULL", description="Evaluation status: FULL, PARTIAL, INVALID")
    eligible_for_leaderboard: bool = Field(True, description="Whether this result is eligible for the official leaderboard")
    is_legacy: bool = Field(False, description="Whether this is a legacy deprecated record")
    profile: Optional[str] = Field("standard", description="Evaluation profile: quick, small, medium, standard, extended")
    sampling_seed: Optional[int] = Field(None, description="Reproducible random sampling seed if sampled")

    model: ModelMetadata
    hardware: HardwareInfo
    tasks: Dict[str, TaskMetric] = Field(..., description="Task-level evaluation results")
    categories: Dict[str, CategoryScore] = Field(..., description="Category-level aggregates")

    slm_index: float = Field(..., ge=0.0, le=100.0, description="Overall normalized aggregate composite score (0-100%)")
    coding_agentic_index: Optional[float] = Field(None, description="Specialized coding and agentic execution index")
    local_efficiency: Optional[Dict[str, Any]] = Field(None, description="Local inference efficiency telemetry metrics")
    notes: Optional[str] = Field(None, description="Evaluation run notes or environment details")
    provenance: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Dataset revisions, prompt template hashes, and seeds")

    def to_summary_dict(self) -> Dict[str, Any]:
        """Compact summary suitable for leaderboard table rendering."""
        return {
            "model_id": self.model.model_id,
            "model_slug": self.model.model_slug,
            "params_b": self.model.param_count_b,
            "param_tier": self.model.param_tier,
            "quantization": self.model.quantization,
            "backend": self.model.backend,
            "status": self.status,
            "eligible_for_leaderboard": self.eligible_for_leaderboard,
            "is_legacy": self.is_legacy,
            "profile": self.profile,
            "slm_index": round(self.slm_index, 2),
            "coding_agentic_index": round(self.coding_agentic_index, 2) if self.coding_agentic_index is not None else None,
            "reasoning": round(self.categories.get("reasoning", CategoryScore(category="reasoning", weight=0.35, normalized_score=0.0, task_count=0)).normalized_score, 2),
            "mathematics": round(self.categories.get("mathematics", CategoryScore(category="mathematics", weight=0.35, normalized_score=0.0, task_count=0)).normalized_score, 2),
            "instruction": round(self.categories.get("instruction", CategoryScore(category="instruction", weight=0.30, normalized_score=0.0, task_count=0)).normalized_score, 2),
            "coding": round(self.categories.get("coding", CategoryScore(category="coding", weight=0.0, normalized_score=0.0, task_count=0)).normalized_score, 2) if "coding" in self.categories else None,
            "tool_calling": round(self.categories.get("tool_calling", CategoryScore(category="tool_calling", weight=0.0, normalized_score=0.0, task_count=0)).normalized_score, 2) if "tool_calling" in self.categories else None,
            "gpu": self.hardware.gpu_name or "CPU",
            "model_ram_gb": self.hardware.model_ram_gb or self.model.model_ram_gb,
            "reasoning_effort": self.model.reasoning_effort,
            "notes": self.notes,
            "timestamp": self.timestamp,
        }
